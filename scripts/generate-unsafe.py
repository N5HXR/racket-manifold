#!/usr/bin/env python3
"""Generate exact Racket FFI declarations from manifoldc.h.

Requires pycparser. The generated module is checked in, so package users do
not need Python or Manifold headers at runtime.
"""

from pathlib import Path
import argparse
from pycparser import c_ast, c_generator, parse_file


SCALARS = {
    "void": "_void",
    "char": "_byte",
    "int": "_int",
    "int32_t": "_int32",
    "uint8_t": "_uint8",
    "uint32_t": "_uint32",
    "uint64_t": "_uint64",
    "size_t": "_size",
    "float": "_float",
    "double": "_double",
    "ManifoldOpType": "_int",
    "ManifoldError": "_int",
    "ManifoldJoinType": "_int",
    "ManifoldVec2": "_manifold-vec2",
    "ManifoldVec3": "_manifold-vec3",
    "ManifoldIVec3": "_manifold-ivec3",
    "ManifoldVec4": "_manifold-vec4",
    "ManifoldManifoldPair": "_manifold-pair",
    "ManifoldRayHit": "_manifold-ray-hit",
    "ManifoldSdf": "_manifold-sdf",
}


def ffi_type(rendered: str) -> str:
    rendered = " ".join(rendered.split())
    if "(*)(double, double, double, void *)" in rendered:
        return "_manifold-warp3"
    if "(*)(double, double, void *)" in rendered:
        return "_manifold-warp2"
    if rendered.startswith("void (*)(double *new_prop"):
        return "_manifold-properties-callback"
    if rendered == "void (*)(char *, void *)":
        return "_manifold-string-callback"
    if "*" in rendered or "[" in rendered:
        return "_pointer"
    try:
        return SCALARS[rendered]
    except KeyError as error:
        raise ValueError(f"unmapped C type: {rendered}") from error


def generate(header: Path) -> str:
    ast = parse_file(
        str(header), use_cpp=True,
        cpp_args=["-E", "-D__attribute__(x)="])
    renderer = c_generator.CGenerator()
    functions = [
        node for node in ast.ext
        if isinstance(node, c_ast.Decl) and isinstance(node.type, c_ast.FuncDecl)
    ]

    lines = [
        "#lang racket/base",
        "",
        ";; Generated by scripts/generate-unsafe.py. Do not edit manually.",
        "(require ffi/unsafe \"library.rkt\")",
        "(provide (all-defined-out))",
        "",
        "(define-cstruct _manifold-vec2 ([x _double] [y _double]))",
        "(define-cstruct _manifold-vec3 ([x _double] [y _double] [z _double]))",
        "(define-cstruct _manifold-ivec3 ([x _int] [y _int] [z _int]))",
        "(define-cstruct _manifold-vec4 ([x _double] [y _double] [z _double] [w _double]))",
        "(define-cstruct _manifold-pair ([first _pointer] [second _pointer]))",
        "(define-cstruct _manifold-ray-hit",
        "  ([face-id _uint64] [distance _double]",
        "   [position _manifold-vec3] [normal _manifold-vec3]))",
        "",
        "(define _manifold-sdf",
        "  (_fun _double _double _double _pointer -> _double))",
        "(define _manifold-warp3",
        "  (_fun _double _double _double _pointer -> _manifold-vec3))",
        "(define _manifold-warp2",
        "  (_fun _double _double _pointer -> _manifold-vec2))",
        "(define _manifold-properties-callback",
        "  (_fun _pointer _manifold-vec3 _pointer _pointer -> _void))",
        "(define _manifold-string-callback",
        "  (_fun _pointer _pointer -> _void))",
        "",
    ]

    for node in functions:
        decl = node.type
        result = ffi_type(renderer.visit(decl.type))
        parameters = [] if decl.args is None else [
            ffi_type(renderer.visit(parameter.type)) for parameter in decl.args.params
        ]
        signature = " ".join(parameters + ["->", result])
        lines.extend([
            f"(define {node.name}",
            f"  (get-ffi-obj \"{node.name}\" manifold-lib (_fun {signature})))",
        ])
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("header", type=Path)
    parser.add_argument("output", type=Path)
    arguments = parser.parse_args()
    arguments.output.write_text(generate(arguments.header))


if __name__ == "__main__":
    main()

